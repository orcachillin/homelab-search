import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import chokidar from "chokidar";
import ts from "typescript";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const componentRoot = path.join(root, "src/client/components");
const outputPath = path.join(root, "src/services/client/generated/componentManifest.ts");
const watchMode = process.argv.includes("--watch");

async function getSourceFiles(directory = componentRoot) {
    const entries = await readdir(directory, { withFileTypes: true });
    const files = await Promise.all(entries.map(async entry => {
        const entryPath = path.join(directory, entry.name);
        if (entry.isDirectory()) return getSourceFiles(entryPath);
        if (!entry.isFile() || !/\.(?:ts|tsx)$/.test(entry.name) || entry.name.endsWith(".d.ts")) return [];
        return [entryPath];
    }));

    return files.flat();
}

function hasComponentRegistration(source, sourcePath) {
    const sourceFile = ts.createSourceFile(
        sourcePath,
        source,
        ts.ScriptTarget.Latest,
        false,
        sourcePath.endsWith(".tsx") ? ts.ScriptKind.TSX : ts.ScriptKind.TS,
    );

    return sourceFile.statements.some(statement =>
        ts.isVariableStatement(statement)
        && statement.modifiers?.some(modifier => modifier.kind === ts.SyntaxKind.ExportKeyword)
        && statement.declarationList.declarations.some(declaration =>
            ts.isIdentifier(declaration.name) && declaration.name.text === "component"
        )
    );
}

async function generate() {
    const sources = [];

    for (const filePath of await getSourceFiles()) {
        const source = await readFile(filePath, "utf8");
        if (hasComponentRegistration(source, filePath)) {
            sources.push(path.relative(componentRoot, filePath).split(path.sep).join("/"));
        }
    }

    sources.sort();

    const entries = sources.map(source => {
        const importPath = `../../../client/components/${source.replace(/\.(?:ts|tsx)$/, ".js")}`;
        return `    { source: ${JSON.stringify(source)}, load: () => import(${JSON.stringify(importPath)}) },`;
    });

    const output = [
        "// Generated by scripts/generate-component-manifest.mjs. Do not edit.",
        "export type ComponentLoader = {",
        "    source: string;",
        "    load: () => Promise<unknown>;",
        "};",
        "",
        "export const componentLoaders = [",
        ...entries,
        "] satisfies readonly ComponentLoader[];",
        "",
    ].join("\n");

    await mkdir(path.dirname(outputPath), { recursive: true });

    let current = "";
    try {
        current = await readFile(outputPath, "utf8");
    } catch (error) {
        if (error.code !== "ENOENT") throw error;
    }

    if (current !== output) {
        await writeFile(outputPath, output);
        console.log(`Generated component manifest with ${sources.length} components.`);
    }
}

await generate();

if (watchMode) {
    let generation = Promise.resolve();
    const watcher = chokidar.watch(componentRoot, { ignoreInitial: true });

    watcher.on("all", (_event, changedPath) => {
        if (!/\.(?:ts|tsx)$/.test(changedPath) || changedPath.endsWith(".d.ts")) return;
        generation = generation.then(generate).catch(error => console.error(error));
    });

    console.log("Watching client components for manifest changes.");
}
